.distribution <- function(benefit, quantity, group) {
  n <- length(benefit)
  ord <- order(quantity)
  bottom <- ord[seq_len(floor(n / 2))]
  tot_b <- sum(benefit)
  tot_q <- sum(quantity)
  metrics <- c(
    gini = .gini(benefit),
    concentration_index = .conc_index(benefit, quantity),
    bottom50_benefit_share = if (tot_b > 0 && length(bottom))
      sum(benefit[bottom]) / tot_b else NA_real_,
    bottom50_quantity_share = if (tot_q > 0 && length(bottom))
      sum(quantity[bottom]) / tot_q else NA_real_,
    share_members_worse_off = mean(benefit < 0))
  by_group <- NULL
  if (!is.null(group)) {
    g <- factor(group, levels = unique(group))
    nb <- tapply(benefit, g, sum)
    nq <- tapply(quantity, g, sum)
    nn <- tapply(benefit, g, length)
    by_group <- data.frame(
      group = levels(g), members = as.numeric(nn),
      member_share = as.numeric(nn) / n,
      quantity_share = if (tot_q > 0) as.numeric(nq) / tot_q else NA,
      benefit_share = if (tot_b != 0) as.numeric(nb) / tot_b else NA,
      benefit_per_member = as.numeric(nb) / as.numeric(nn),
      benefit_per_unit = ifelse(as.numeric(nq) > 0,
                                as.numeric(nb) / as.numeric(nq), NA),
      stringsAsFactors = FALSE)
  }
  list(metrics = metrics, by_group = by_group)
}

.allocate_dividend <- function(pool, quantity, rule, equity) {
  n <- length(quantity)
  if (pool <= 0) return(rep(0, n))
  w <- switch(rule,
              patronage = quantity,
              equity = equity,
              equal = rep(1, n))
  if (sum(w) <= 0) return(rep(0, n))
  pool * w / sum(w)
}

#' Member-level distributional accounting of FPO benefits
#'
#' Separates the total surplus generated by a farmer producer organisation
#' (FPO) from the benefits actually received by member farmers.
#'
#' **FPO account.** The FPO buys members' produce at `member_price`, sells
#' it at `sale_price`, incurs handling costs per unit and fixed operating
#' costs, and may run an input business buying at `input_bulk_price` and
#' selling to members at `input_member_price`. Its net surplus is
#' \deqn{S = \sum_i q_i (p^{sale} - p^{m}_i - h) + \sum_i x_i
#'   (w^{m} - w^{bulk}) - F.}
#' A share `dividend_share` of positive surplus is distributed as dividends;
#' the rest is retained.
#'
#' **Member account.** Relative to the member's outside option (selling
#' individually at `outside_price` with transaction cost `outside_cost` and
#' buying inputs at `input_market_price`), member \eqn{i} gains
#' \deqn{B_i = q_i (p^m_i - p^{out}_i) + q_i (c^{out}_i - c^m_i) +
#'   x_i (w^{mkt} - w^{m}) + D_i.}
#'
#' **Value created** is \eqn{\sum_i (B_i - D_i) + S}, which equals
#' \eqn{\sum_i B_i} plus retained surplus. The member share of value
#' created shows how much of the FPO's economic contribution actually
#' reaches farmers. Distribution across members is summarised by the Gini
#' coefficient of benefits (when all benefits are non-negative), the
#' concentration index of benefits ranked by quantity marketed (positive
#' values mean benefits are concentrated among larger suppliers), the
#' benefit share of the smallest half of suppliers compared with their
#' quantity share, the share of members made worse off, and, if `group` is
#' given, benefit shares and benefit per member by group (for example
#' marginal, small, medium and large farmers).
#'
#' Per-member arguments accept a scalar or one value per member. Per-unit
#' transaction costs can be taken from [transaction_costs()].
#'
#' @param quantity Quantity each member sells through the FPO.
#' @param outside_price Price each member would receive outside the FPO.
#' @param member_price Price the FPO pays each member.
#' @param sale_price Price the FPO realises when selling the pooled
#'   produce.
#' @param outside_cost Member transaction cost per unit outside the FPO.
#' @param member_cost Member transaction cost per unit when delivering to
#'   the FPO.
#' @param handling_cost FPO handling, grading and transport cost per unit.
#' @param fixed_cost FPO fixed operating cost for the period (staff, rent,
#'   compliance, depreciation).
#' @param input_quantity Quantity of inputs each member buys through the
#'   FPO.
#' @param input_market_price Price of inputs in the open market.
#' @param input_member_price Price the FPO charges members for inputs.
#' @param input_bulk_price Price the FPO pays for inputs in bulk.
#' @param dividend_share Share of positive FPO surplus paid out as
#'   dividends (0 to 1).
#' @param dividend_rule How dividends are allocated: `"patronage"` (in
#'   proportion to quantity), `"equity"` (in proportion to `equity`) or
#'   `"equal"` (equal per member).
#' @param equity Share capital held by each member; required for
#'   `dividend_rule = "equity"`.
#' @param group Optional farm-size or social group of each member.
#' @param member_id Optional member identifiers.
#'
#' @return A list of class `member_benefit` with
#'   \describe{
#'     \item{members}{Data frame of benefit components per member:
#'       `price_gain`, `cost_saving`, `input_saving`, `dividend` and
#'       `total`.}
#'     \item{fpo}{Named vector: output margin, input margin, fixed cost,
#'       net surplus, dividends paid and retained surplus.}
#'     \item{value}{Named vector: value created, total member benefit,
#'       retained surplus, member share of value created, member benefit per
#'       unit marketed.}
#'     \item{distribution}{List with `metrics` and `by_group`.}
#'   }
#'
#' @examples
#' q <- c(5, 8, 12, 20, 35, 60)
#' size <- c("marginal", "marginal", "small", "small", "medium", "large")
#' mb <- member_benefit(q, outside_price = 1400, member_price = 1480,
#'                      sale_price = 1650, outside_cost = 140,
#'                      member_cost = 40, handling_cost = 60,
#'                      fixed_cost = 8000, input_quantity = q / 5,
#'                      input_market_price = 1350, input_member_price = 1300,
#'                      input_bulk_price = 1250, dividend_share = 0.5,
#'                      group = size)
#' mb
#' mb$distribution$by_group
#' @export
member_benefit <- function(quantity, outside_price, member_price, sale_price,
                           outside_cost = 0, member_cost = 0,
                           handling_cost = 0, fixed_cost = 0,
                           input_quantity = 0, input_market_price = 0,
                           input_member_price = 0, input_bulk_price = 0,
                           dividend_share = 0,
                           dividend_rule = c("patronage", "equity", "equal"),
                           equity = NULL, group = NULL, member_id = NULL) {
  .chk(quantity, "quantity", lower = 0, scalar = FALSE)
  n <- length(quantity)
  dividend_rule <- match.arg(dividend_rule)
  vec <- list(outside_price = outside_price, member_price = member_price,
              outside_cost = outside_cost, member_cost = member_cost,
              input_quantity = input_quantity)
  for (nm in names(vec)) .chk(vec[[nm]], nm, lower = 0, scalar = FALSE)
  sc <- list(sale_price = sale_price, handling_cost = handling_cost,
             fixed_cost = fixed_cost, input_market_price = input_market_price,
             input_member_price = input_member_price,
             input_bulk_price = input_bulk_price)
  for (nm in names(sc)) .chk(sc[[nm]], nm, lower = 0)
  .chk(dividend_share, "dividend_share", 0, 1)
  po <- .expand(outside_price, n, "outside_price")
  pm <- .expand(member_price, n, "member_price")
  co <- .expand(outside_cost, n, "outside_cost")
  cm <- .expand(member_cost, n, "member_cost")
  iq <- .expand(input_quantity, n, "input_quantity")
  if (dividend_rule == "equity") {
    if (is.null(equity)) {
      stop("`equity` is required when `dividend_rule = \"equity\"`.",
           call. = FALSE)
    }
    .chk(equity, "equity", lower = 0, scalar = FALSE)
    equity <- .expand(equity, n, "equity")
  }
  if (!is.null(group) && length(group) != n) {
    stop("`group` must have one value per member.", call. = FALSE)
  }
  if (is.null(member_id)) member_id <- seq_len(n)

  out_margin <- sum(quantity * (sale_price - pm - handling_cost))
  in_margin <- sum(iq * (input_member_price - input_bulk_price))
  surplus <- out_margin + in_margin - fixed_cost
  pool <- max(surplus, 0) * dividend_share
  retained <- surplus - pool

  price_gain <- quantity * (pm - po)
  cost_saving <- quantity * (co - cm)
  input_saving <- iq * (input_market_price - input_member_price)
  dividend <- .allocate_dividend(pool, quantity, dividend_rule, equity)
  total <- price_gain + cost_saving + input_saving + dividend

  members <- data.frame(member = member_id, quantity = quantity,
                        price_gain = price_gain, cost_saving = cost_saving,
                        input_saving = input_saving, dividend = dividend,
                        total = total,
                        per_unit = ifelse(quantity > 0, total / quantity, NA),
                        stringsAsFactors = FALSE)
  if (!is.null(group)) members$group <- group

  value_created <- sum(total) + retained
  Q <- sum(quantity)
  out <- list(
    members = members,
    fpo = c(output_margin = out_margin, input_margin = in_margin,
            fixed_cost = fixed_cost, net_surplus = surplus,
            dividends = pool, retained = retained),
    value = c(value_created = value_created, member_benefit = sum(total),
              retained = retained,
              member_share = if (value_created > 0)
                sum(total) / value_created else NA_real_,
              member_benefit_per_unit = if (Q > 0) sum(total) / Q else NA),
    distribution = .distribution(total, quantity, group))
  class(out) <- "member_benefit"
  out
}

#' @export
print.member_benefit <- function(x, ...) {
  f <- x$fpo
  v <- x$value
  m <- x$distribution$metrics
  cat("FPO surplus and member benefit accounting\n\n")
  cat("FPO account\n")
  cat("  Output margin:          ", .fmt(f[["output_margin"]]), "\n", sep = "")
  cat("  Input margin:           ", .fmt(f[["input_margin"]]), "\n", sep = "")
  cat("  Fixed cost:             ", .fmt(f[["fixed_cost"]]), "\n", sep = "")
  cat("  Net surplus:            ", .fmt(f[["net_surplus"]]), "\n", sep = "")
  cat("  Dividends / retained:   ", .fmt(f[["dividends"]]), " / ",
      .fmt(f[["retained"]]), "\n\n", sep = "")
  cat("Value created:            ", .fmt(v[["value_created"]]), "\n", sep = "")
  cat("Received by members:      ", .fmt(v[["member_benefit"]]), " (",
      .pct(v[["member_share"]]), ")\n", sep = "")
  cat("Member benefit per unit:  ", .fmt(v[["member_benefit_per_unit"]]),
      "\n\n", sep = "")
  comp <- colSums(x$members[, c("price_gain", "cost_saving", "input_saving",
                                "dividend")])
  cat("Benefit channels: price ", .fmt(comp[1]), ", transaction cost ",
      .fmt(comp[2]), ", inputs ", .fmt(comp[3]), ", dividends ",
      .fmt(comp[4]), "\n", sep = "")
  cat("Distribution: Gini ", .fmt(m[["gini"]], 3), ", concentration index ",
      .fmt(m[["concentration_index"]], 3), "; smallest half of suppliers ",
      "receive ", .pct(m[["bottom50_benefit_share"]]), " of benefits for ",
      .pct(m[["bottom50_quantity_share"]]), " of volume; ",
      .pct(m[["share_members_worse_off"]]), " of members worse off\n",
      sep = "")
  invisible(x)
}
