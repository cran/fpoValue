#' fpoValue: Farmer Producer Organisation Economics and Member Benefit
#' Accounting
#'
#' Tools to assess when collective marketing, aggregation, grading and bulk
#' procurement through a farmer producer organisation (FPO) improve
#' member-farmer returns.
#'
#' * [transaction_costs()] - per-farmer transaction costs of a marketing
#'   channel.
#' * [aggregation_savings()] - scale economies from consolidated transport,
#'   bulk input purchase and grading.
#' * [member_benefit()] - member-level distributional accounting that
#'   separates total FPO surplus from benefits received by farmers.
#' * [break_even_volume()] - throughput, membership and procurement price
#'   needed for the FPO to break even.
#' * [collective_marketing_scenarios()] - comparison of individual and
#'   collective marketing channels for the same members.
#'
#' Quantities may be in any unit (for example quintals or tonnes) and
#' prices and costs in currency per the same unit, provided they are used
#' consistently.
#'
